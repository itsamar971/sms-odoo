const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
const OUT = process.env.DEMO_OUT || path.join(__dirname, 'out');
const BASE = process.env.BASE_URL || 'http://localhost:3000';
const W = 1440, H = 900;
const SEG = JSON.parse(fs.readFileSync(path.join(OUT, 'segments.json'), 'utf8'));
const INIT = fs.readFileSync(path.join(__dirname, 'overlay.js'), 'utf8');

(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: W, height: H }, recordVideo: { dir: path.join(OUT, 'video'), size: { width: W, height: H } } });
  await ctx.addInitScript(INIT);
  const page = await ctx.newPage();
  const t0 = Date.now();
  const log = [];
  const wait = (ms) => page.waitForTimeout(ms);
  let busyUntil = 0;
  const setCap = (text) => page.evaluate((t) => { sessionStorage.setItem('__cap', t); const c = document.getElementById('__caption'); if (c) { c.textContent = t; c.style.display = t ? 'block' : 'none'; } }, text).catch(() => {});
  const say = async (key) => {
    const now = Date.now();
    if (busyUntil > now) await wait(busyUntil - now);
    await setCap(SEG[key].caption);
    log.push({ key, t: (Date.now() - t0) / 1000 });
    busyUntil = Date.now() + SEG[key].dur * 1000 + 450;
  };
  const done = async () => { const now = Date.now(); if (busyUntil > now) await wait(busyUntil - now); };
  const moveTo = async (loc) => {
    await loc.scrollIntoViewIfNeeded();
    const b = await loc.boundingBox();
    await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2, { steps: 20 });
    await wait(300);
  };
  const click = async (loc, after = 1000) => { loc = loc.first(); await moveTo(loc); await loc.click(); await wait(after); };
  const type = async (loc, text) => { await moveTo(loc); await loc.click(); await loc.fill(''); await loc.pressSequentially(text, { delay: 60 }); await wait(400); };
  const scroll = async (dy, steps = 8) => { for (let i = 0; i < steps; i++) { await page.mouse.wheel(0, dy / steps); await wait(110); } await wait(500); };
  const go = async (path) => { await page.goto(BASE + path, { waitUntil: 'networkidle' }); await wait(400); };

  await go('/login');
  await say('intro1'); await say('intro2');
  await say('login');
  await moveTo(page.getByRole('button', { name: /^Admin/ })); await wait(6000);
  await done();
  await page.getByRole('button', { name: /^Admin/ }).click(); await page.waitForURL('**/dashboard'); await wait(1200);

  await say('dash1');
  for (const i of [0, 1, 2, 3, 4, 5]) { await moveTo(page.locator('main .grid').first().locator('> *').nth(i)); await wait(1300); }
  await done();
  await say('dash2');
  await moveTo(page.locator('.recharts-surface').first());
  await page.mouse.move(700, 450, { steps: 30 }); await wait(1500);
  await moveTo(page.locator('.recharts-surface').nth(1));
  await done();
  await say('dash3');
  await scroll(650);
  await wait(2500);
  await click(page.getByRole('button', { name: /^Chase/ }), 2000);
  await moveTo(page.locator('.recharts-surface').nth(2));
  await done();

  await go('/products');
  await say('prod1');
  await wait(3500);
  await click(page.getByRole('link', { name: 'Accounting Suite' }), 1500);
  await done();
  await say('prod2');
  await moveTo(page.getByText('Brand: Odoo, Edition: Enterprise')); await wait(2500);
  await moveTo(page.getByText('₹4,259.00')); await done();
  await say('prod3');
  await scroll(450); await done();
  await go('/plans');
  await say('plans'); await moveTo(page.getByText('Legacy Starter (sunset)')); await done();
  await go('/discounts');
  await say('disc'); await wait(7000); await moveTo(page.getByText('usage limit reached')); await done();

  await go('/templates');
  await say('tmpl1'); await wait(3500);
  await moveTo(page.getByRole('link', { name: 'Create quotation' }).first()); await done();
  await page.getByRole('link', { name: 'Create quotation' }).first().click(); await page.waitForURL('**/subscriptions/new?template=*'); await wait(1200);
  await say('tmpl2');
  const sel = page.locator('select').first();
  await moveTo(sel); await sel.selectOption({ index: 1 }); await wait(800); await done();
  await say('tmpl3');
  await scroll(350); await wait(5000);
  await moveTo(page.getByRole('button', { name: 'Create quotation' })); await wait(1500);
  await page.getByRole('button', { name: 'Create quotation' }).click();
  await page.waitForURL(/\/subscriptions\/[a-z0-9]+$/); await wait(1000);
  await done();
  await say('sm1');
  await moveTo(page.locator('ol').first()); await wait(9000);
  await click(page.getByRole('button', { name: 'Confirm', exact: true }), 2000);
  await click(page.getByRole('button', { name: 'Activate' }), 1500);
  await done();
  await say('sm2');
  await moveTo(page.getByRole('button', { name: 'Pause' })); await wait(3000);
  await moveTo(page.getByText('Total per period')); await wait(2000);
  await done();
  await click(page.getByRole('button', { name: 'Bill now' }), 1500);
  await say('sm3'); await scroll(500); await done();

  await go('/billing');
  await say('bill1'); await wait(6000);
  await moveTo(page.getByRole('button', { name: 'Run Billing Now' })); await done();
  await page.getByRole('button', { name: 'Run Billing Now' }).click(); await page.getByText('Billing run complete').waitFor(); await wait(800);
  await say('bill2'); await moveTo(page.getByText('Auto-closed').first()); await done();
  await page.getByRole('button', { name: 'Run Billing Now' }).click(); await wait(1500);
  await say('bill3'); await moveTo(page.getByText('Created', { exact: true })); await done();
  await say('bill4'); await scroll(500); await done();

  await go('/invoices?status=DRAFT');
  await click(page.locator('table a').first(), 1500);
  await say('inv1');
  await moveTo(page.locator('tr', { hasText: 'Discount' }).first()).catch(() => {});
  await wait(4000);
  await done();
  await click(page.getByRole('button', { name: 'Confirm', exact: true }), 1500);
  await say('inv2');
  await click(page.getByRole('button', { name: 'Record payment' }), 800);
  const amt = page.locator('[role=dialog] input').first();
  const due = Number(await amt.inputValue());
  await type(amt, String((due + 500).toFixed(2)));
  await click(page.getByRole('button', { name: 'Save payment' }), 800);
  await done();
  await say('inv3');
  await type(amt, '1000');
  await click(page.getByRole('button', { name: 'Save payment' }), 2000);
  await moveTo(page.getByText('Amount due').last());
  await done();
  await say('inv4');
  await click(page.getByRole('button', { name: 'Record payment' }), 1000);
  await click(page.getByRole('button', { name: 'Save payment' }), 2500);
  await moveTo(page.getByRole('link', { name: 'PDF' })); await wait(1200);
  await moveTo(page.getByRole('button', { name: 'Send by email' }));
  await done();

  await go('/subscriptions');
  await say('list1');
  await moveTo(page.getByText(/^of/).first()).catch(() => {});
  await wait(2500);
  await click(page.getByRole('button', { name: /Recurring/ }), 1500);
  const st = page.locator('select').first(); await moveTo(st); await st.selectOption('PAUSED'); await wait(1500);
  await done();
  await go('/reports');
  await say('rep1'); await scroll(500); await wait(1500);
  await moveTo(page.getByRole('link', { name: /CSV/ }).last()); await done();

  await say('portal1'); await moveTo(page.getByTitle('Sign out')); await done();
  await page.getByTitle('Sign out').click(); await page.waitForURL('**/login'); await wait(800);
  await click(page.getByRole('button', { name: /^Customer portal/ }), 0); await page.waitForURL('**/portal'); await wait(1200);
  await say('portal2'); await moveTo(page.getByText('Balance due')); await wait(3000); await moveTo(page.getByText('Recent invoices').first()).catch(() => {}); await scroll(-2000); await done();
  await click(page.getByRole('link', { name: /^Quotations/ }), 600);
  await say('portal3'); await moveTo(page.getByRole('button', { name: 'Accept quotation' })); await done();
  await click(page.getByRole('link', { name: /^Active/ }), 600);
  await say('portal4'); await click(page.getByRole('button', { name: 'Pause' }), 900); await click(page.getByRole('button', { name: 'Pause' }).last(), 1200); await done();
  await say('portal5'); await scroll(1000);
  await click(page.getByRole('button', { name: 'Pay' }), 1000); await click(page.getByRole('button', { name: 'Save payment' }), 1200); await done();
  await page.goto(BASE + '/dashboard'); await page.waitForURL('**/portal'); await wait(600);
  await say('rbac'); await done();
  await say('outro'); await done(); await wait(1500);

  await page.close();
  const v = await page.video().path();
  await ctx.close(); await browser.close();
  fs.writeFileSync(path.join(OUT, 'timeline.json'), JSON.stringify(log, null, 1));
  console.log('VIDEO', v, 'segments', log.length);
})().catch((e) => { console.error('FAIL', e); process.exit(1); });
